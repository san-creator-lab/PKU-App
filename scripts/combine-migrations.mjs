// Concatenates supabase/migrations/*.sql into docs/setup/all-migrations.sql
// so a hosted project can be initialized by pasting ONE file into the
// Supabase Dashboard SQL editor — no CLI install required.
// Run: npm run gen:sql (checked-in output; regenerate after schema changes)
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const dir = path.join(root, 'supabase/migrations')
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()

const parts = [
  `-- Hero Fuel — all migrations combined for the Supabase SQL editor.
-- GENERATED by scripts/combine-migrations.mjs — do not edit by hand.
--
-- Usage: Supabase Dashboard -> SQL Editor -> New query -> paste this whole
-- file -> Run. Run it ONCE on a fresh project. (Teams that use the CLI
-- should run \`npx supabase db push\` with supabase/migrations/ instead —
-- same content, and the CLI then tracks migration history.)
`,
]

for (const file of files) {
  parts.push(`\n-- ============================================================\n-- ${file}\n-- ============================================================\n`)
  parts.push(readFileSync(path.join(dir, file), 'utf8'))
}

mkdirSync(path.join(root, 'docs/setup'), { recursive: true })
const out = path.join(root, 'docs/setup/all-migrations.sql')
writeFileSync(out, parts.join('\n'))
console.log(`Wrote ${out} (${files.length} migrations)`)
