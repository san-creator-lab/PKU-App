// Generates src/lib/data/seedFoods.ts from the SQL seed migration so the
// keyless LocalBackend serves exactly the same base library as Supabase.
// The migration is the single source of truth. Run: npm run gen:foods
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const sql = readFileSync(
  path.join(root, 'supabase/migrations/20260707100005_seed_foods.sql'),
  'utf8',
)

const rowRe =
  /\(\s*'((?:[^']|'')+)',\s*([\d.]+),\s*([\d.]+),\s*'((?:[^']|'')*)',\s*'((?:[^']|'')+)',\s*'([^']*)'\s*\)/g

const unescape = (s) => s.replaceAll("''", "'")
const foods = []
for (const m of sql.matchAll(rowRe)) {
  foods.push({
    name: unescape(m[1]),
    protein_per_100g: Number(m[2]),
    protein_per_serving: Number(m[3]),
    serving_description: unescape(m[4]),
    category: unescape(m[5]),
    emoji: m[6] || null,
  })
}

if (foods.length < 50) {
  console.error(`Parsed only ${foods.length} foods — check the regex/migration`)
  process.exit(1)
}

const out = `// AUTO-GENERATED by scripts/gen-seed-foods.mjs from
// supabase/migrations/20260707100005_seed_foods.sql — do not edit by hand.
// Regenerate with: npm run gen:foods

export interface SeedFood {
  name: string
  protein_per_100g: number
  protein_per_serving: number
  serving_description: string
  category: string
  emoji: string | null
}

export const seedFoods: SeedFood[] = ${JSON.stringify(foods, null, 2)}
`

mkdirSync(path.join(root, 'src/lib/data'), { recursive: true })
writeFileSync(path.join(root, 'src/lib/data/seedFoods.ts'), out)
console.log(`Wrote ${foods.length} foods to src/lib/data/seedFoods.ts`)
